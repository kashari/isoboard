export interface RegistryEntry {
  component: ComponentType<SolidProps>;
  label: string;
  description: string;
  icon: string;
  color: NodeColor;
  defaultData: Record<string, unknown>;
  inspectorFields: string[];
  paletteGroup: string;
  modes: Mode[];
}
function entry(
  label: string,
  description: string,
  icon: string,
  color: NodeColor,
  paletteGroup: string,
  inspectorFields: string[] = [],
  modes: Mode[] = ["architecture"],
): RegistryEntry {
  return {
    component: NodeSolid,
    label,
    description,
    icon,
    color,
    paletteGroup,
    modes,
    defaultData: {},
    inspectorFields,
  };
}
